#!/usr/bin/env node
import Ajv from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const destination = path.join(root, "src/data/validators/generated");
// Match each existing consumer's exact schema source and Ajv options. Do not
// sync or mutate A-owned schemas here; changed schemas regenerate on build.
const jobs = [
  {
    name: "ops",
    source: "../contracts/ops.schema.json",
    options: { allErrors: true, multipleOfPrecision: 8 },
  },
  {
    name: "ops-calendar",
    source: "src/data/contracts/ops.schema.json",
    calendar: true,
    options: { allErrors: true, strictNumbers: true },
  },
  ...["1.2", "1.3", "1.4", "1.5"].map((version) => ({
    name: `replay-${version}`,
    source: `src/data/contracts/${version === "1.5" ? "replay" : `replay-${version}`}.schema.json`,
    options: { allErrors: true, strictNumbers: true, strictTypes: false },
  })),
  {
    name: "agent-detail",
    source: "src/data/contracts/agent-detail.schema.json",
    options: { allErrors: true, strictNumbers: true, strictTypes: false },
  },
];
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Usage: node scripts/generate-validators.mjs [--check]");
let changed = false;
for (const job of jobs) {
  const original = await readFile(path.resolve(root, job.source), "utf8");
  const schema = JSON.parse(original);
  const ajv = new Ajv({ ...job.options, code: { source: true, esm: true } });
  addFormats(ajv);
  const validate = ajv.compile(job.calendar ? schema.oneOf[1] : schema);
  const code = standaloneCode(ajv, validate);
  // Bundle only standalone format/runtime helpers into a browser-native ESM
  // module: no CommonJS require, Ajv constructor, compiler, or schema loading.
  const result = await build({
    stdin: {
      contents: code,
      resolveDir: root,
      sourcefile: `${job.name}.standalone.js`,
    },
    bundle: true,
    platform: "browser",
    format: "esm",
    target: "es2022",
    minify: true,
    write: false,
    legalComments: "none",
  });
  const sha = createHash("sha256").update(original).digest("hex");
  const header = `// Generated by scripts/generate-validators.mjs; DO NOT EDIT.\n// Source: ${job.source}${job.calendar ? "#/oneOf/1" : ""}; SHA-256: ${sha}\n`;
  const outputs = {
    [`${job.name}.js`]: header + result.outputFiles[0].text,
    [`${job.name}.d.ts`]:
      header +
      'import type { SchemaValidator } from "../types";\nexport const validate: SchemaValidator;\nexport default validate;\n',
  };
  for (const [name, content] of Object.entries(outputs)) {
    const file = path.join(destination, name);
    let previous;
    try {
      previous = await readFile(file, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (previous === content) continue;
    changed = true;
    if (check) {
      console.error(`Stale validator: ${path.relative(root, file)}`);
      continue;
    }
    await mkdir(destination, { recursive: true });
    await writeFile(file, content);
  }
}
if (check && changed) process.exitCode = 1;
else
  console.log(
    `${jobs.length} standalone validators ${check ? "up to date" : "generated"}.`,
  );
